/* TRIGGERS */
/* 
Los triggers son para que cuando se cumpla cierta condición dada, se lance la acción que tiene el trigger
La estructura de creación de un trigger es la siguiente:
CREATE TRIGGER NOMBREDISP MOMENTODISP EVENTODISP
ON TABLA
FOR EACH ROW SENTENDIADISP

MOMENTODISP -> Cuando entra en acción. Puede ser BEFORE o AFTER
EVENTODISP -> Con qué sentencia se activa dicho trigger. Puede ser INSERT, UPDATE o DELETE

NO SE PUEDEN HACER EN VISTAS!!!
*/

