-- DELIMITER // -- SIRVE PARA CAMBIAR EL INDICADOR DE FIN DE LINEA. PASA DE SER DE ; A //
USE PINACOTECAS;
DELIMITER //
CREATE TRIGGER VerificacionAltura
BEFORE INSERT ON CUADRO
FOR EACH ROW
BEGIN
    DECLARE DISPONIBLE INT;
    SELECT PINA_MAX_ALTO INTO DISPONIBLE
    FROM PINACOTECA
    WHERE PINA_NOMBRE = NEW.CUAD_PINA_NOMBRE;
    IF NEW.CUAD_ALTO > DISPONIBLE THEN
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'MUY ALTO EL CUADRO PARA ESTA PINACOTECA';
    END IF;
END;
//
DELIMITER ;
