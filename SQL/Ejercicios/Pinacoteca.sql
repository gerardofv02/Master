DELIMITER //
DROP TRIGGER IF EXISTS PinaActualizada//
CREATE TRIGGER PinaActualizada
AFTER UPDATE ON PINACOTECA
FOR EACH ROW
BEGIN
	IF OLD.PINA_DIRECCION <> NEW.PINA_DIRECCION THEN
		INSERT INTO PINACOTECA_H VALUES (OLD.PINA_NOMBRE, OLD.PINA_CIUDAD, OLD.PINA_DIRECCION, OLD.PINA_SUPERFICIE);
	END IF;
END;
//
DELIMITER ;

